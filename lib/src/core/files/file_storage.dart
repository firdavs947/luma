import 'dart:typed_data';

/// Хранилище пользовательских файлов библиотеки.
///
/// Файл лежит в приватном каталоге приложения: он недоступен другим
/// приложениям и не попадает в общие пользовательские папки, поэтому
/// импортированную музыку нельзя скачать или открыть извне.
abstract interface class FileStorage {
  /// Доступно ли локальное хранилище на текущей платформе.
  bool get isSupported;

  /// Сохраняет файл в приватном каталоге и возвращает `file://`-ссылку.
  Future<String> save({required String fileName, required Uint8List bytes});

  /// Удаляет ранее сохранённый файл.
  Future<void> delete(String location);

  /// Существует ли файл по ссылке.
  ///
  /// Проверка не читает содержимое целиком: библиотека пользуется ей, чтобы
  /// отсеять записи, файлы которых пропали вместе с переустановкой
  /// приложения или очисткой данных.
  Future<bool> exists(String location);

  /// Читает сохранённый файл; `null` — файла нет или он недоступен.
  Future<Uint8List?> read(String location);
}
