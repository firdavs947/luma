import 'media_item.dart';

/// Страница результатов поиска.
///
/// Помимо самих элементов отдаёт признак [hasMore]: выдача источника
/// может быть страничной, и без него интерфейс не знал бы, нужно ли
/// показывать кнопку «Показать ещё».
class MusicSearchPage {
  const MusicSearchPage({required this.items, required this.hasMore});

  /// Элементы текущей страницы.
  final List<MediaItem> items;

  /// Есть ли в источнике ещё результаты за пределами этой страницы.
  final bool hasMore;

  static const empty = MusicSearchPage(items: [], hasMore: false);
}

/// Источник музыкального контента.
///
/// Каталог не знает, откуда приходит музыка — из Genius или из локального
/// набора. Благодаря этому источник можно заменить (например, на вызовы
/// собственного бэкенда) или подменить в тестах, не трогая экраны.
abstract interface class MusicSource {
  /// Курируемая лента музыки для главного экрана и разделов каталога.
  Future<List<MediaItem>> featured();

  /// Поиск музыки по запросу пользователя.
  ///
  /// [offset] — сколько результатов уже показано: источник вернёт
  /// следующую страницу, поэтому длинная выдача не обрывается на первых
  /// двадцати позициях.
  Future<MusicSearchPage> search(String query, {int offset = 0});
}
