import 'genius_models.dart';

/// Источник музыкального контента Genius.
///
/// Слой представления зависит только от этого интерфейса, поэтому реализацию
/// можно заменить, не трогая экраны: например, перевести вызовы на свой
/// бэкенд, чтобы токен не попадал в приложение, или подменить данные в тестах.
///
/// Genius — база текстов песен: у него нет ни длительности треков, ни
/// аудио-превью, а поиск возвращает только песни. Поэтому альбомы получаются
/// через `/songs/{id}` (данные альбома) и `/albums/{id}/tracks` (треклист).
abstract interface class GeniusRepository {
  /// Количество песен на странице поиска: больше Genius не отдаёт.
  static const searchPageSize = 10;

  /// Настроен ли источник (задан ли токен доступа).
  bool get isConfigured;

  /// Поиск песен по названию, исполнителю или строке из текста.
  Future<List<GeniusSong>> searchSongs(String query);

  /// Песня по идентификатору — вместе с данными альбома.
  ///
  /// Нужна, чтобы из результата поиска или списка песен исполнителя получить
  /// альбом: в этих выдачах объекта альбома нет.
  Future<GeniusSong> getSong(String id);

  /// Альбом по идентификатору вместе с ПОЛНЫМ треклистом.
  Future<GeniusAlbum> getAlbum(String id);

  /// Популярные песни исполнителя — из них собирается лента каталога.
  Future<List<GeniusSong>> songsByArtist(
    String artistId, {
    int perPage = 20,
    int page = 1,
  });
}
